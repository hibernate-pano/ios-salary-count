/// 中国法定节假日数据（内置，不联网）。
///
/// 数据来源：国务院办公厅关于部分节假日安排的通知。
/// `isWorkday=false` 为放假日，`isWorkday=true` 为调休补班日（该周末需上班）。
///
/// 维护：每年国务院 12 月左右发布次年安排，届时在此补充新年份数据。
///
/// ## 关于 2027 / 2028 的可信度（必须看懂再改）
///
/// 这两年国务院**还没发布**正式安排，所以数据分两部分：
///
/// - **节日日期是准的**：春节、端午、中秋由农历决定，用系统农历（`Calendar(identifier: .chinese)`）
///   逐日扫描得出，不靠手算。校验方法：同一套代码算 2026 年，得到的
///   春节 2/17、端午 6/19、中秋 9/25 与国务院已发布的 2026 安排**完全一致**。
/// - **放假区间与调休是推算的**：按 2026 的实际做法外推（春节 9 天、国庆 7 天、
///   清明/劳动/端午/中秋 3 天、劳动与国庆各补 2 天班）。
///
/// ⚠️ 官方安排发布后**必须回来核对**，尤其是：放假天数、补班日期、
/// 以及「元旦/清明/劳动/端午/中秋与周末相邻」时的连休与调休安排。
/// 最坏情况是某人被算成工作日而实际放假（或少算一天工资），不会崩溃。
enum HolidayData {

    /// 数据的可信程度。
    ///
    /// 这不是注释，是**能被断言的代码** —— 目的是让「哪些年份还是推算的」这件事
    /// 不会因为没人记得而一直烂着。
    enum Confidence: String {
        /// 国务院已发布正式安排，数据照抄。
        case official
        /// 节日日期准（农历换算），但放假区间与调休是按往年做法外推的。
        /// **官方安排发布后必须回来替换成 `.official`。**
        case extrapolated
    }

    /// 每年数据的可信程度。新增年份必须在这里表态，不能默认混过去。
    static let confidence: [Int: Confidence] = [
        2026: .official,
        2027: .extrapolated,
        2028: .extrapolated,
    ]

    /// 已内置数据的年份集合。新增年份数据时同步更新此处。
    static let supportedYears: Set<Int> = [2026, 2027, 2028]

    /// 还没换成官方数据的年份（按年份升序）。
    ///
    /// UI 可以据此提示，测试据此守住「别把推算数据当成真的发出去」。
    static var extrapolatedYears: [Int] {
        confidence.filter { $0.value == .extrapolated }.keys.sorted()
    }

    /// 指定年份的数据是否仍是外推的。
    static func isExtrapolated(year: Int) -> Bool {
        confidence[year] == .extrapolated
    }

    /// 取指定年份的节假日数据；无数据返回空数组（退化为按星期几判断）。
    static func holidays(year: Int) -> [HolidayConfig] {
        switch year {
        case 2026: return year2026
        case 2027: return year2027
        case 2028: return year2028
        default: return []
        }
    }

    /// 当前年份的节假日数据。
    static func currentYear(calendar: Calendar = .current, now: Date = Date()) -> [HolidayConfig] {
        holidays(year: calendar.component(.year, from: now))
    }

    /// 指定年份是否已内置法定节假日数据。
    /// false 时工作日判断退化为「按星期几」，节假日/调休会算错——UI 应提示用户。
    static func hasData(year: Int) -> Bool {
        supportedYears.contains(year)
    }

    /// 当前年份是否已内置节假日数据。
    static func hasDataForCurrentYear(calendar: Calendar = .current, now: Date = Date()) -> Bool {
        hasData(year: calendar.component(.year, from: now))
    }

